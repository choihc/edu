export const VOCABULARY = RAW.map(([word, reading, meaning, sinoKorean, hint, example, exampleKr, row]) => ({
  id: `${word}|${reading}`,
  word,
  reading,
  meaning,
  sinoKorean,
  hint,
  example,
  exampleKr,
  row,
}));

const BY_ID = new Map(VOCABULARY.map((item) => [item.id, item]));

/**
 * @param {string} id
 * @returns {VocabularyItem | undefined}
 */
export function findById(id) {
  return BY_ID.get(id);
}

/** @returns {string[]} 전체 학습 항목 식별자 */
export function allIds() {
  return VOCABULARY.map((item) => item.id);
}
